import { chromium } from 'playwright-core';
const OUT = process.argv[2];
const b = await chromium.launch({ channel: 'chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const n = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; n.on('pageerror', e => errs.push(e.message));
await n.goto('http://localhost:5179'); await n.selectOption('#lg-user', 'TRBLDESK'); await n.click('button[type=submit]'); await n.waitForTimeout(6000);
const t0 = Date.now();
await n.getByRole('button', { name: 'Yard map', exact: true }).first().click();
await n.waitForFunction(() => { const f = document.querySelector('iframe'); return f && !f.classList.contains('invisible'); }, null, { timeout: 30000 });
console.log('first map shown after', Date.now() - t0, 'ms'); await n.waitForTimeout(2500);
await n.screenshot({ path: OUT + '/island-HY.png' });
const f = n.frameLocator('iframe');
await f.getByRole('button', { name: 'Return' }).last().click(); await n.waitForTimeout(800);
console.log('after Return, iframe hidden:', await n.evaluate(() => !!document.querySelector('iframe')?.closest('.hidden')), '| home visible:', await n.getByRole('heading', { name: /Yards and shops/ }).isVisible());
await n.getByRole('button', { name: 'Switch between light and dark theme' }).click();
const t1 = Date.now();
await n.getByRole('button', { name: 'Shop map', exact: true }).first().click();
await n.waitForFunction(() => { const f = document.querySelector('iframe'); return f && !f.classList.contains('invisible') && !f.closest('.hidden'); }, null, { timeout: 30000 });
console.log('second map shown after', Date.now() - t1, 'ms'); await n.waitForTimeout(2500);
await n.screenshot({ path: OUT + '/island-HY-shop-dark.png' });
console.log(errs.join('\n') || 'no page errors'); await b.close();
